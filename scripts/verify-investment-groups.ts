import assert from "node:assert/strict";
import { parseSaveInvestmentGroupInput, parseDeleteInvestmentGroupInput, type DashboardHoldingAllocationSummary } from "@family-ledger/shared";
import { buildGroupDistribution } from "../apps/api/src/services/groupAllocationService";

const id = (n: number) => `00000000-0000-4000-8000-${String(n).padStart(12, "0")}`;
const row = (n: number, value: string | null): DashboardHoldingAllocationSummary => ({ id: id(n), name: `Security ${n}`, assetType: "etf", allocationType: "instrument", marketValue: value, percentageOfTotal: null });
const allocations: DashboardHoldingAllocationSummary[] = [row(1,"30000.00"),row(2,"15000.00"),row(3,"25000.00"),row(4,"20000.00"),row(5,"10000.00"),{...row(6,"10000.00"),id:"cash",name:"现金",assetType:"cash",allocationType:"cash"}];
const configuration = {revision:"9007199254740993",groups:[{id:id(10),name:"纳斯达克100",instrumentIds:[id(1),id(2),id(3),id(99)]},{id:id(11),name:"Empty",instrumentIds:[]}]};
const original = structuredClone(allocations);
const build = (rows = allocations, totalAssets: string | null = "110000.00") => buildGroupDistribution({allocations:rows,totalAssets,configuration});
const result = build();
assert.equal(result.rows[0].marketValue,"70000.00");
assert.equal(result.rows[0].percentageOfTotal,"63.64");
assert.equal(result.rows[0].members.length,3);
assert.equal(result.rows.find(r=>r.id===`instrument:${id(5)}`)?.marketValue,"10000.00");
assert.equal(result.rows.at(-1)?.id,"cash");
assert.deepEqual(allocations,original);
assert.equal(result.revision,"9007199254740993");
assert.equal(build([row(1,null),row(2,"2")]).rows[0].marketValue,null);
const negative = build([row(1,"-1"),row(2,"2")]);
assert.equal(negative.rows[0].marketValue,"1.00");
assert.equal(negative.reason,"negative_value");
assert(negative.rows.every(r=>r.percentageOfTotal===null));
assert.equal(build(allocations,"0").reason,"non_positive_total");
assert.equal(build(allocations,null).reason,"missing_valuation");
assert.equal(build([row(1,"0.01"),row(2,"0.02")]).rows[0].marketValue,"0.03");
assert.equal(build([row(1,"0")]).rows.length,1);
assert.equal(build([]).rows.length,0);
assert.equal(build([row(4,"1")]).rows[0].members.length,1);
assert.equal(buildGroupDistribution({allocations,totalAssets:"110000",configuration:{revision:"0",groups:[]}}).rows.length,6);
const valid = {name:"　中文 😀　",instrumentIds:[id(1)],expectedRevision:"0"};
assert.equal(parseSaveInvestmentGroupInput(valid).name,"中文 😀");
assert.equal(parseSaveInvestmentGroupInput({...valid,name:"😀".repeat(32)}).name.length,64);
for(const patch of [{name:" "},{name:"😀".repeat(33)},{instrumentIds:[id(1),id(1)]},{instrumentIds:["bad"]},{expectedRevision:0},{expectedRevision:"01"},{scopeKey:"ledger"}]) assert.throws(()=>parseSaveInvestmentGroupInput({...valid,...patch}));
assert.deepEqual(parseDeleteInvestmentGroupInput({expectedRevision:"2"}),{expectedRevision:"2"});
assert.throws(()=>parseDeleteInvestmentGroupInput({expectedRevision:"-1"}));
assert.throws(()=>parseDeleteInvestmentGroupInput({expectedRevision:"1",scope_key:"ledger"}));
console.log("Investment grouping: exact sums, source invalidity, scoped contributors, identity, immutability and input validation passed.");
